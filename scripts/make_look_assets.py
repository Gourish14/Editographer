"""Makes the free LUTs and SFX. Spec: specs/09-local-setup.md#setupbat-run-once

Style LUTs and the fallback log LUT are written by this script, so they are ours, not DJI's.
The only DJI file is its official Osmo 360 LUT, fetched with a checksum from DJI's own server.
SFX come from FFmpeg's noise and sine sources. Standard library only, safe to re-run.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from collections.abc import Callable, Sequence
from pathlib import Path

from download_models import DownloadError, ModelSpec, download

ROOT = Path(__file__).resolve().parent.parent
CUBE_SIZE = 33
SAMPLE_RATE = 48000
LUMA_R, LUMA_G, LUMA_B = 0.2126, 0.7152, 0.0722

DJI_LUT = ModelSpec(
    name="dji-osmo-360-dlogm-to-rec709",
    phase=3,
    url="https://terra-1-g.djicdn.com/851d20f7b9f64838a34cd02351370894/OQ101%20LUT/"
    "DJI%20Osmo%20360%20D-Log%20M%20to%20Rec.709%20V1.cube",
    path="dji_osmo360_dlogm_to_rec709.cube",
    size=1042315,
    sha256="b18162854ab47702068410c33afa98a8cb6eef159fc5a04ce0e65fad0fd8947e",
)
GENERIC_LOG_LUT = "generic_log_to_rec709.cube"

Rgb = tuple[float, float, float]
Look = Callable[[float, float, float], Rgb]


def _clamp(value: float) -> float:
    return min(1.0, max(0.0, value))


def _luma(red: float, green: float, blue: float) -> float:
    return LUMA_R * red + LUMA_G * green + LUMA_B * blue


def _contrast(value: float, amount: float) -> float:
    """S-curve around middle grey. Amount 0 changes nothing."""
    smooth = value * value * (3.0 - 2.0 * value)
    return value + (smooth - value) * amount


def _saturate(rgb: Rgb, amount: float) -> Rgb:
    grey = _luma(*rgb)
    red, green, blue = rgb
    return (
        grey + (red - grey) * amount,
        grey + (green - grey) * amount,
        grey + (blue - grey) * amount,
    )


def _tone(rgb: Rgb, contrast: float, saturation: float, tint: Rgb = (0.0, 0.0, 0.0)) -> Rgb:
    red, green, blue = _saturate(rgb, saturation)
    return (
        _contrast(red, contrast) + tint[0],
        _contrast(green, contrast) + tint[1],
        _contrast(blue, contrast) + tint[2],
    )


def teal_orange(red: float, green: float, blue: float) -> Rgb:
    """Shadows lean teal and highlights lean orange."""
    toned = _tone((red, green, blue), 0.5, 1.05)
    light = _luma(red, green, blue)
    shadow = 1.0 - light
    return (
        toned[0] + 0.10 * light - 0.08 * shadow,
        toned[1] + 0.01 * light + 0.02 * shadow,
        toned[2] - 0.10 * light + 0.08 * shadow,
    )


def film(red: float, green: float, blue: float) -> Rgb:
    """Soft contrast, lifted blacks, a little warmth."""
    toned = _tone((red, green, blue), 0.35, 0.9, (0.012, 0.0, -0.012))
    return tuple(0.04 + value * 0.93 for value in toned)  # type: ignore[return-value]


def vibrant(red: float, green: float, blue: float) -> Rgb:
    return _tone((red, green, blue), 0.25, 1.3)


def saturated(red: float, green: float, blue: float) -> Rgb:
    return _tone((red, green, blue), 0.3, 1.5)


def warm(red: float, green: float, blue: float) -> Rgb:
    return _tone((red, green, blue), 0.2, 1.1, (0.035, 0.008, -0.035))


def moody(red: float, green: float, blue: float) -> Rgb:
    toned = _tone((red, green, blue), 0.6, 0.75, (-0.01, 0.0, 0.015))
    return tuple(value * 0.92 for value in toned)  # type: ignore[return-value]


def punchy(red: float, green: float, blue: float) -> Rgb:
    return _tone((red, green, blue), 0.75, 1.15)


def generic_log_to_rec709(red: float, green: float, blue: float) -> Rgb:
    """A plain log-to-display guess, used only when DJI's LUT could not be fetched."""
    return _tone((red, green, blue), 1.0, 1.35)


STYLE_LOOKS: dict[str, Look] = {
    "teal_orange": teal_orange,
    "film": film,
    "vibrant": vibrant,
    "saturated": saturated,
    "warm": warm,
    "moody": moody,
    "punchy": punchy,
}


def cube_text(title: str, look: Look, size: int = CUBE_SIZE) -> str:
    """A .cube file. Red changes fastest, as the format requires."""
    last = size - 1
    lines = [
        f'TITLE "{title}"',
        "# Generated by scripts/make_look_assets.py for Editographer. Not a DJI LUT.",
        f"LUT_3D_SIZE {size}",
    ]
    for blue in range(size):
        for green in range(size):
            for red in range(size):
                mapped = look(red / last, green / last, blue / last)
                lines.append(" ".join(f"{_clamp(value):.6f}" for value in mapped))
    return "\n".join(lines) + "\n"


def write_luts(folder: Path) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    for name, look in STYLE_LOOKS.items():
        (folder / f"{name}.cube").write_text(cube_text(name, look), encoding="ascii")
    generic = cube_text("generic log to rec709", generic_log_to_rec709)
    (folder / GENERIC_LOG_LUT).write_text(generic, encoding="ascii")


def whoosh_command(target: Path) -> list[str]:
    """Filtered noise that swells to its peak at 0.25 s, the time the brain plans around."""
    swell = "volume='pow(sin(PI*t/0.5),3)':eval=frame"
    return [
        "-f",
        "lavfi",
        "-i",
        f"anoisesrc=color=pink:seed=7:sample_rate={SAMPLE_RATE}:duration=0.5",
        "-af",
        f"highpass=f=300,lowpass=f=5000,{swell},volume=10dB,alimiter=limit=0.95:level=disabled",
        "-ac",
        "2",
        str(target),
    ]


def impact_command(target: Path) -> list[str]:
    """A falling sub tone with a short noise crack on top."""
    tone = "sin(2*PI*(55*t+30*(1-exp(-20*t))/20))*exp(-5*t)"
    crack = "0.35*(2*random(0)-1)*exp(-60*t)"
    return [
        "-f",
        "lavfi",
        "-i",
        f"aevalsrc=exprs='{tone}+{crack}':sample_rate={SAMPLE_RATE}:duration=1.2",
        "-af",
        "alimiter=limit=0.95:level=disabled",
        "-ac",
        "2",
        str(target),
    ]


def write_sfx(folder: Path, ffmpeg: str = "ffmpeg") -> None:
    folder.mkdir(parents=True, exist_ok=True)
    for name, command in (("whoosh", whoosh_command), ("impact", impact_command)):
        subprocess.run(
            [ffmpeg, "-hide_banner", "-loglevel", "error", "-y", *command(folder / f"{name}.wav")],
            check=True,
        )


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Make the free LUTs and SFX.")
    parser.add_argument("--luts-dir", type=Path, default=ROOT / "luts")
    parser.add_argument("--sfx-dir", type=Path, default=ROOT / "sfx")
    args = parser.parse_args(argv)

    write_luts(args.luts_dir)
    print(f"Style LUTs: {len(STYLE_LOOKS)} written, plus the generic log fallback")
    if shutil.which("ffmpeg") is None:
        print("ERROR: FFmpeg is not on PATH, so the SFX were not made.", file=sys.stderr)
        return 1
    write_sfx(args.sfx_dir)
    print("SFX: whoosh and impact written")
    try:
        print(f"{DJI_LUT.name}: {download(DJI_LUT, args.luts_dir)}")
    except DownloadError as error:
        # Not fatal: renders fall back to the generic LUT and say so in the log.
        print(f"WARNING: DJI's LUT was not fetched, using the generic one ({error})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
